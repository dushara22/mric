function setLanguage(lang) {
  const dict = translations[lang] || translations.ru;

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (dict[key] !== undefined) {
      element.innerHTML = dict[key];
    }
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === lang;

    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try {
    localStorage.setItem("sdyushor-lang", lang);
  } catch (error) {
    // Сайт продолжит работать, если localStorage недоступен.
  }
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

const visionButton = document.getElementById("visionToggle");

visionButton.addEventListener("click", () => {
  const active = document.body.classList.toggle("visually-impaired");

  visionButton.setAttribute("aria-pressed", String(active));

  const lang = document.documentElement.lang;
  const normalLabel = {
    ru: "Обычная версия",
    be: "Звычайная версія",
    en: "Standard view"
  };

  visionButton.querySelector("[data-i18n]").textContent = active
    ? normalLabel[lang] || normalLabel.ru
    : translations[lang].vision;
});

const menuButton = document.getElementById("menuToggle");
const navigation = document.getElementById("mainNav");

menuButton.addEventListener("click", () => {
  const isOpen = navigation.classList.toggle("open");

  menuButton.setAttribute("aria-expanded", String(isOpen));
  menuButton.textContent = isOpen ? "✕" : "☰";
});

navigation.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    navigation.classList.remove("open");
    menuButton.setAttribute("aria-expanded", "false");
    menuButton.textContent = "☰";
  });
});

try {
  const savedLanguage = localStorage.getItem("sdyushor-lang");

  if (savedLanguage && translations[savedLanguage]) {
    setLanguage(savedLanguage);
  }
} catch (error) {
  // Если localStorage недоступен, используется русский язык.
}
